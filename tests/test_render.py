def test_describe_check():
    cases = [
        (chk(name="init", args=["init"]), "**init**: run `./run.sh init`, expect exit code 0"),
        (chk(name="pong", do="tcp", input="PING\r\n", expect="+PONG\r\n"),
         '**pong**: send `"PING\\r\\n"`, expect reply `"+PONG\\r\\n"` (exact)'),
        (chk(name="fixture", do="write", path="a.txt", input="hi"), '**fixture**: write `"hi"` to `a.txt`'),
        (chk(name="head", do="file", path=".git/HEAD", expect="ref: refs/heads/main\n"),
         '**head**: `.git/HEAD` exists with content `"ref: refs/heads/main\\n"` (exact)'),
        (chk(name="commit", args=["commit", "-m", "it's done"]),
         "**commit**: run `./run.sh commit -m 'it'\\''s done'`, expect exit code 0"),
        (chk(name="hash", args=["hash-object", "a.txt"], expect=r"^[0-9a-f]{40}\n$", match="regex"),
         "**hash**: run `./run.sh hash-object a.txt`, expect exit code 0 and stdout `^[0-9a-f]{40}\\n$` (regex)"),
        (chk(name="big", do="write", path="big.txt", input="a" * 500),
         '**big**: write `"' + "a" * 120 + '"`… (500 bytes) to `big.txt`'),
    ]
    for c, want in cases:
        assert describe_check(c) == want


def test_shell_quote():
    assert shell_quote("a/b-c.txt") == "a/b-c.txt"
    assert shell_quote("") == "''"
    assert shell_quote("a b") == "'a b'"


def test_contract_runs_in_the_callers_directory():
    for p in (Program(kind="server", port=6379), Program(kind="cli", port=0)):
        c = contract(p)
        assert "in the directory `run.sh` was called from" in c and "relative to `run.sh` itself" in c


def test_fenced_hint_left_alone(sample_spec):
    sample_spec.steps[0].detail.hints[2] = "```go\nfor {}\n```"
    md = render_step(sample_spec, 0).decode()
    assert "```text" not in md and "```go\nfor {}\n```" in md
